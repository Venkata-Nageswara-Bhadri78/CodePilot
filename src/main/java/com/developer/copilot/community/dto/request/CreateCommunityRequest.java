package com.developer.copilot.community.dto.request;

import java.util.ArrayList;
import java.util.List;

import com.developer.copilot.community.exception.CommunityValidationException;
import com.developer.copilot.community.service.CommunityLimits;
import com.developer.copilot.community.service.CommunityMessages;
import com.fasterxml.jackson.annotation.JsonAnySetter;

import io.swagger.v3.oas.annotations.media.Schema;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Size;
import lombok.Getter;
import lombok.Setter;

@Getter
@Setter
@Schema(description = "Creates a community for a posting. The community name is generated by the server. "
        + "The owner is the authenticated user. jobId must be a job that user saved.")
public class CreateCommunityRequest {

    @Schema(description = "Saved job id owned by the signed-in user. It is not the community id.", example = "12")
    @NotNull(message = "Job id is required.")
    private Long jobId;

    @NotBlank(message = "Title is required.")
    @Size(max = CommunityLimits.MAX_TITLE_LENGTH, message = "Title cannot exceed 255 characters.")
    private String title;

    @NotBlank(message = "Company is required.")
    @Size(max = CommunityLimits.MAX_COMPANY_LENGTH, message = "Company cannot exceed 255 characters.")
    private String company;

    @Size(max = CommunityLimits.MAX_LOCATION_LENGTH, message = "Location cannot exceed 255 characters.")
    private String location;

    @NotBlank(message = CommunityMessages.DESCRIPTION_REQUIRED)
    @Size(max = CommunityLimits.MAX_DESCRIPTION_LENGTH, message = "Description cannot exceed 50000 characters.")
    private String description;

    @Schema(description = "Primary posting URL. This becomes the canonical posting identity after normalization.",
            example = "https://jobs.example.com/openings/backend-engineer")
    @NotBlank(message = "Posting URL is required.")
    @Size(max = CommunityLimits.MAX_URL_LENGTH, message = "Posting URL cannot exceed 2000 characters.")
    private String sourceUrl;

    @Schema(description = "Other URLs for the same posting. They are not proof of a match by themselves until saved as aliases.")
    @Size(max = CommunityLimits.MAX_URL_ALIASES, message = "Too many alternative posting URLs.")
    private List<@NotBlank(message = "Alternative posting URL cannot be blank.") @Size(max = CommunityLimits.MAX_URL_LENGTH, message = "Posting URL cannot exceed 2000 characters.") String> alternativeUrls = new ArrayList<>();

    @Schema(description = "When true, the description is rewritten before it is stored. A model failure keeps this description and still creates the community.",
            example = "false")
    private Boolean refineDescription;

    @JsonAnySetter
    public void rejectUnknownField(String name, Object ignored) {
        throw new CommunityValidationException(CommunityMessages.UNKNOWN_FIELD);
    }
}
