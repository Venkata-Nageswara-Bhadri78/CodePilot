package com.developer.copilot.community.controller;

import java.time.LocalDateTime;

import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;

import com.developer.copilot.common.dto.ApiResponse;
import com.developer.copilot.community.dto.CommunityMatchOutcome;
import com.developer.copilot.community.dto.request.CreateCommunityRequest;
import com.developer.copilot.community.dto.request.RefineCommunityDescriptionRequest;
import com.developer.copilot.community.dto.request.ResolveCommunityRequest;
import com.developer.copilot.community.dto.response.CommunityCreateResponse;
import com.developer.copilot.community.dto.response.CommunityDescriptionResponse;
import com.developer.copilot.community.dto.response.CommunityMatchResponse;
import com.developer.copilot.community.dto.response.CommunityPrefillResponse;
import com.developer.copilot.community.service.CommunityCreationService;
import com.developer.copilot.community.service.CommunityMessages;

import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.media.Content;
import io.swagger.v3.oas.annotations.media.Schema;
import io.swagger.v3.oas.annotations.responses.ApiResponses;
import io.swagger.v3.oas.annotations.security.SecurityRequirement;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.validation.Valid;

@Tag(name = "Community",
        description = "Resolve a real-world job posting and create its community. "
                + "A URL match does not join the user. The community name is generated by the server.")
@RestController
@RequestMapping("/api/v1/community")
@SecurityRequirement(name = "Bearer Authentication")
public class CommunityController {

    private final CommunityCreationService communityCreationService;

    public CommunityController(CommunityCreationService communityCreationService) {
        this.communityCreationService = communityCreationService;
    }

    @Operation(summary = "Prefill community creation from a saved job",
            description = "Requires a current community account. The job must belong to the signed-in user. "
                    + "Returns permitted job fields and whether a community already exists for that posting URL. "
                    + "Does not create a community or a membership.")
    @ApiResponses({
            @io.swagger.v3.oas.annotations.responses.ApiResponse(responseCode = "200", description = "Permitted job fields and match"),
            @io.swagger.v3.oas.annotations.responses.ApiResponse(responseCode = "401", description = "Missing or invalid JWT",
                    content = @Content(schema = @Schema(implementation = ApiResponse.class))),
            @io.swagger.v3.oas.annotations.responses.ApiResponse(responseCode = "403", description = "Community account, terms, extension client, or incomplete username",
                    content = @Content(schema = @Schema(implementation = ApiResponse.class))),
            @io.swagger.v3.oas.annotations.responses.ApiResponse(responseCode = "404", description = "Job missing or not owned by the caller",
                    content = @Content(schema = @Schema(implementation = ApiResponse.class)))
    })
    @GetMapping("/jobs/{jobId}/prefill")
    public ResponseEntity<ApiResponse<CommunityPrefillResponse>> prefill(@PathVariable Long jobId) {
        CommunityPrefillResponse prefill = communityCreationService.prefill(jobId);
        return ResponseEntity.ok(envelope(prefill.getMatch().getMessage(), prefill));
    }

    @Operation(summary = "Resolve posting URLs to a community",
            description = "Normalizes the URLs and looks up aliases. Does not create a community and does not join one.")
    @ApiResponses({
            @io.swagger.v3.oas.annotations.responses.ApiResponse(responseCode = "200", description = "Match outcome. EXISTING_COMMUNITY includes a safe summary."),
            @io.swagger.v3.oas.annotations.responses.ApiResponse(responseCode = "400", description = "Missing URLs or unknown field",
                    content = @Content(schema = @Schema(implementation = ApiResponse.class))),
            @io.swagger.v3.oas.annotations.responses.ApiResponse(responseCode = "401", description = "Missing or invalid JWT",
                    content = @Content(schema = @Schema(implementation = ApiResponse.class))),
            @io.swagger.v3.oas.annotations.responses.ApiResponse(responseCode = "403", description = "Community account, terms, extension client, or incomplete username",
                    content = @Content(schema = @Schema(implementation = ApiResponse.class)))
    })
    @PostMapping("/resolve")
    public ResponseEntity<ApiResponse<CommunityMatchResponse>> resolve(
            @Valid @RequestBody ResolveCommunityRequest request) {
        CommunityMatchResponse match = communityCreationService.resolve(request);
        return ResponseEntity.ok(envelope(match.getMessage(), match));
    }

    @Operation(summary = "Create a community for a posting",
            description = "Creates the community, its URL aliases, and the creator membership in one transaction. "
                    + "If the posting already has a community, returns that community and does not join the caller. "
                    + "refineDescription rewrites the description before insert; a model failure still creates the community "
                    + "with the submitted description. The caller's saved job is not modified.")
    @ApiResponses({
            @io.swagger.v3.oas.annotations.responses.ApiResponse(responseCode = "201", description = "Community created and the caller is a member"),
            @io.swagger.v3.oas.annotations.responses.ApiResponse(responseCode = "200", description = "Posting already has a community. The caller is not joined."),
            @io.swagger.v3.oas.annotations.responses.ApiResponse(responseCode = "400", description = "Invalid fields or unknown JSON",
                    content = @Content(schema = @Schema(implementation = ApiResponse.class))),
            @io.swagger.v3.oas.annotations.responses.ApiResponse(responseCode = "401", description = "Missing or invalid JWT",
                    content = @Content(schema = @Schema(implementation = ApiResponse.class))),
            @io.swagger.v3.oas.annotations.responses.ApiResponse(responseCode = "403", description = "Community account, terms, extension client, or incomplete username",
                    content = @Content(schema = @Schema(implementation = ApiResponse.class))),
            @io.swagger.v3.oas.annotations.responses.ApiResponse(responseCode = "404", description = "Job missing or not owned by the caller",
                    content = @Content(schema = @Schema(implementation = ApiResponse.class))),
            @io.swagger.v3.oas.annotations.responses.ApiResponse(responseCode = "409", description = "URL is too vague or the URLs belong to different communities",
                    content = @Content(schema = @Schema(implementation = ApiResponse.class)))
    })
    @PostMapping
    public ResponseEntity<ApiResponse<CommunityCreateResponse>> create(
            @Valid @RequestBody CreateCommunityRequest request) {
        CommunityCreateResponse created = communityCreationService.create(request);
        HttpStatus status = created.getOutcome() == CommunityMatchOutcome.CREATED
                ? HttpStatus.CREATED
                : HttpStatus.OK;
        return ResponseEntity.status(status).body(envelope(created.getMessage(), created));
    }

    @Operation(summary = "Refine a description for community display",
            description = "Sends only the description to the existing AI service. "
                    + "On failure the original text is returned and nothing is stored.")
    @ApiResponses({
            @io.swagger.v3.oas.annotations.responses.ApiResponse(responseCode = "200", description = "Refined text, or the original text when the model cannot be used"),
            @io.swagger.v3.oas.annotations.responses.ApiResponse(responseCode = "400", description = "Missing description or unknown field",
                    content = @Content(schema = @Schema(implementation = ApiResponse.class))),
            @io.swagger.v3.oas.annotations.responses.ApiResponse(responseCode = "401", description = "Missing or invalid JWT",
                    content = @Content(schema = @Schema(implementation = ApiResponse.class))),
            @io.swagger.v3.oas.annotations.responses.ApiResponse(responseCode = "403", description = "Community account, terms, extension client, or incomplete username",
                    content = @Content(schema = @Schema(implementation = ApiResponse.class)))
    })
    @PostMapping("/descriptions/refine")
    public ResponseEntity<ApiResponse<CommunityDescriptionResponse>> refine(
            @Valid @RequestBody RefineCommunityDescriptionRequest request) {
        CommunityDescriptionResponse refined = communityCreationService.refine(request.getDescription());
        String message = refined.isRefined()
                ? CommunityMessages.REFINED
                : CommunityMessages.REFINEMENT_KEPT_ORIGINAL;
        return ResponseEntity.ok(envelope(message, refined));
    }

    private static <T> ApiResponse<T> envelope(String message, T data) {
        return ApiResponse.<T>builder()
                .success(true)
                .message(message)
                .data(data)
                .timestamp(LocalDateTime.now())
                .build();
    }
}
